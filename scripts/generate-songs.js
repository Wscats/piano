// Main generation
// -----------------------------------------------------------------------

function main() {
  const rng = new SeededRandom(42)
  const songs = []
  const categoryKeys = Object.keys(SONG_NAMES)
  const numCategories = categoryKeys.length

  // Track used names to ensure uniqueness
  const usedNames = new Set()

  for (let i = 0; i < TOTAL_SONGS; i++) {
    const category = categoryKeys[i % numCategories]
    const namePool = SONG_NAMES[category]
    const nameIdx = Math.floor(i / numCategories) % namePool.length

    const baseName = namePool[nameIdx]
    const variation = Math.floor(i / (numCategories * namePool.length))
    let name = variation > 0 ? `${baseName} Vol.${variation + 1}` : baseName

    // Ensure uniqueness
    if (usedNames.has(name)) {
      let suffix = 2
      while (usedNames.has(`${name} (${suffix})`)) suffix++
      name = `${name} (${suffix})`
    }
    usedNames.add(name)

    const noteCount = rng.nextInt(24, 100)
    const noteArray = generateSong(rng, noteCount)

    songs.push({ id: i + 1, name, category, notes: noteArray })

    if ((i + 1) % 1000 === 0) {
      process.stdout.write(`  Generated ${i + 1} / ${TOTAL_SONGS} songs...\r`)
    }
  }

  console.log(`\n  Building output file...`)

  // Build output in chunks to avoid huge string concatenation
  const chunks = []
  chunks.push(`/**
 * Piano Song Library — ${TOTAL_SONGS} Songs
 * Auto-generated by scripts/generate-songs.js
 *
 * Each song: { id, name, category, notes: string[] }
 * Note format: simplified notation (1-7, +/- for octave, # for sharp, . for dotted)
 */

const songLibrary = [\n`)

  for (let i = 0; i < songs.length; i++) {
    const s = songs[i]
    const notesStr = s.notes.map(n => `'${n}'`).join(',')
    chunks.push(`{id:${s.id},name:'${s.name.replace(/'/g, "\\'")}',category:'${s.category}',notes:[${notesStr}]}`)
    if (i < songs.length - 1) chunks.push(',\n')
  }

  chunks.push(`\n]

export default songLibrary
`)

  const output = chunks.join('')
  const outPath = path.join(__dirname, '..', 'src', 'elements', 'app-piano', 'songs', 'song-library.js')
  fs.writeFileSync(outPath, output, 'utf8')
  const sizeKB = (Buffer.byteLength(output) / 1024).toFixed(1)
  const sizeMB = (Buffer.byteLength(output) / 1024 / 1024).toFixed(2)
  console.log(`✅ Generated ${songs.length} songs → ${outPath}`)
  console.log(`   File size: ${sizeKB} KB (${sizeMB} MB)`)
  console.log(`   Categories: ${numCategories}`)
}

main()
