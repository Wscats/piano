// -----------------------------------------------------------------------
// Song generation engine (enhanced)
// -----------------------------------------------------------------------

function generateSong(rng, noteCount) {
  const scaleKeys = Object.keys(SCALES)
  const scaleKey = rng.pick(scaleKeys)
  const scale = SCALES[scaleKey]

  const notes = []
  let phraseLength = rng.nextInt(4, 8)
  let currentPhrase = 0

  const octavePrefixes = ['', '-', '+', '', '', '']  // bias toward middle octave
  let currentOctave = rng.pick(octavePrefixes)

  // Pick a primary melodic pattern for this song (for coherence)
  const primaryPattern = rng.pick(MELODIC_PATTERNS)
  const secondaryPattern = rng.pick(MELODIC_PATTERNS)

  for (let i = 0; i < noteCount; i++) {
    if (currentPhrase >= phraseLength) {
      currentPhrase = 0
      phraseLength = rng.nextInt(4, 8)
      if (rng.next() < 0.25) {
        currentOctave = rng.pick(octavePrefixes)
      }
    }

    // Use primary pattern 70% of the time, secondary 30%
    const pattern = rng.next() < 0.7 ? primaryPattern : secondaryPattern
    const patternIdx = currentPhrase % pattern.length
    const scaleIdx = pattern[patternIdx] % scale.length

    let note = scale[scaleIdx]

    // Apply octave shift
    if (currentOctave && !note.startsWith('+') && !note.startsWith('-')) {
      note = currentOctave + note
    }

    // Rhythm
    const rhythm = rng.pick(RHYTHM_PATTERNS)
    const rhythmIdx = currentPhrase % rhythm.length
    const dots = rhythm[rhythmIdx]
    note += '.'.repeat(dots)

    // Occasional sharp
    if (rng.next() < 0.04 && !note.includes('#')) {
      const digitIdx = note.search(/[0-9]/)
      if (digitIdx >= 0) {
        note = note.slice(0, digitIdx) + '#' + note.slice(digitIdx)
      }
    }

    // Occasional chord
    if (rng.next() < 0.06) {
      const chordIdx = (scaleIdx + 2) % scale.length
      let chordNote = scale[chordIdx]
      if (currentOctave && !chordNote.startsWith('+') && !chordNote.startsWith('-')) {
        chordNote = currentOctave + chordNote
      }
      note = note + chordNote
    }

    notes.push(note)
    currentPhrase++
  }

  return notes
}

